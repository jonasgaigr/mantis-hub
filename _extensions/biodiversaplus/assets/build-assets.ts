/**
 * Regenerates `_assets.scss` from the binary/vector assets in this folder.
 *
 * Quarto compiles `theme.scss` to `<doc>_files/libs/revealjs/dist/theme/quarto-*.css`
 * and copies `url(...)` references through verbatim, so a relative path such as
 * `url("assets/logo-mask.svg")` would resolve against that generated directory and
 * 404. Inlining the assets as data URIs sidesteps path resolution entirely and keeps
 * the deck working after `?print-pdf`, `embed-resources: true`, or moving the HTML.
 *
 * Run it after replacing any of the files it reads:
 *
 *     quarto run _extensions/biodiversaplus/assets/build-assets.ts
 *
 * (`quarto run` uses the Deno that ships with Quarto - nothing extra to install.)
 */

const here = new URL(".", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const read = (f: string) => Deno.readFileSync(`${here}${f}`);

const b64 = (bytes: Uint8Array) => {
  let s = "";
  for (let i = 0; i < bytes.length; i += 0x8000) {
    s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  }
  return btoa(s);
};

// SVG stays human-readable as a percent-encoded URI: smaller than base64 and it
// keeps the mask diffable in version control.
const svgUri = (bytes: Uint8Array) => {
  const text = new TextDecoder().decode(bytes).replace(/\s*\n\s*/g, " ").trim();
  return "data:image/svg+xml," + encodeURIComponent(text).replace(/%20/g, " ");
};

// Everything on the closing slide *except* its logo mark: the slide rectangle and
// the mark's own subpaths in one even-odd path, so the mark - stars and swirl
// still filled, because those are already holes in it - becomes transparent.
// Masking the header band and the mark's white halo with this lets the photograph
// sit on the slide's own `background-image`, where a relative url() in an author's
// inline style resolves against the document instead of against this stylesheet.
const closingMark = new TextDecoder().decode(read("closing-mask.svg"))
  .match(/ d="([^"]+)"/)![1];
const closingInverse =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 8000 4500" width="8000" height="4500">` +
  `<path fill="#fff" fill-rule="evenodd" d="M0 0L8000 0L8000 4500L0 4500Z${closingMark}"/></svg>`;

const mask = svgUri(read("logo-mask.svg"));
const field = svgUri(read("title-field.svg"));
const closing = svgUri(read("closing-field.svg"));
const closingCut = svgUri(new TextEncoder().encode(closingInverse));
const png = (f: string) => "data:image/png;base64," + b64(read(f));
const logo = png("logo-full.png");
const logoEu = png("logo-eu.png");
const iconWeb = png("icon-web.png");
const iconMail = png("icon-mail.png");
const iconSocial = png("icon-social.png");

const out = `// GENERATED by build-assets.ts - do not edit by hand.
// Re-run: quarto run _extensions/biodiversaplus/assets/build-assets.ts

// Silhouette of the Biodiversa+ logo mark, traced from the transparent region of
// ppt/media/image8.png in the source deck. Slide-space viewBox (0 0 8000 4500), so
// it can be applied to a full-slide element with no positioning maths.
$bd-logo-mask: url("${mask}");

// The title slide's colour field, traced from the same artwork. The white area
// around the logo mark is an outline of varying width rather than the circle a
// naive fit suggests, so the field is extracted rather than modelled.
$bd-title-field: url("${field}");

// The closing slide's colour field, traced the same way from ppt/media/image9.png.
// Unlike the title slide the field runs edge to edge below the header band, and the
// mark sits inside it as a hole with its own white outline - so the hole is part of
// the field rather than something the mark's own silhouette can produce.
$bd-closing-field: url("${closing}");

// The complement of the closing slide's mark: opaque everywhere except the mark
// itself, which is where the slide's own background-image (the photograph) is
// left showing. Derived from closing-mask.svg, which is traced separately from
// logo-mask.svg because the title slide's copy of the mark bleeds off the right
// edge of the artwork and is clipped there, while the closing slide's is whole.
$bd-closing-cut: url("${closingCut}");

// Full-colour logo (mark + wordmark + tagline), cropped at native resolution from
// ppt/media/image1.png and downsampled to 1200px wide.
$bd-logo-full: url("${logo}");

// "EUROPEAN PARTNERSHIP" + the EU emblem + "Co-funded by the European Union", the
// funding lockup that the source deck puts in the closing slide's header band only.
// Cropped from ppt/media/image9.png at x 4077-7731, y 554-978 of 8000x4500.
$bd-logo-eu: url("${logoEu}");

// The closing slide's contact-line icons (ppt/media/image10-12.png), white on
// transparent, downsampled to 128px. They display at ~25 CSS px.
$bd-icon-web: url("${iconWeb}");
$bd-icon-mail: url("${iconMail}");
$bd-icon-social: url("${iconSocial}");
`;

Deno.writeTextFileSync(`${here}_assets.scss`, out);
console.log(`wrote _assets.scss (${(out.length / 1024).toFixed(1)} KB)`);
